// utilities
function formatDate(dateString) {
    const months = ['Jan', 'Feb', 'Mar', 'Apr', 'Mei', 'Jun', 'Jul', 'Agu', 'Sep', 'Okt', 'Nov', 'Des'];
    const date = new Date(dateString);
    return `${date.getDate()} ${months[date.getMonth()]} ${date.getFullYear()}`;
}

// API-like functions (simulate async)
function getLatestNews(limit = 3) {
    return new Promise(resolve => {
        setTimeout(() => {
            const sorted = [...newsDatabase].sort((a, b) => new Date(b.date) - new Date(a.date));
            resolve(sorted.slice(0, limit));
        }, 300);
    });
}

function getAllNews(category = 'all', page = 1, perPage = 6, sort = 'newest') {
    return new Promise((resolve) => {
        setTimeout(() => {
            let filtered = category === 'all'
                ? [...newsDatabase]
                : newsDatabase.filter(news => news.category === category);

            // SORTING BERDASARKAN TANGGAL
            if (sort === 'newest') {
                filtered.sort((a, b) => new Date(b.date) - new Date(a.date)); // Terbaru dulu
            } else {
                filtered.sort((a, b) => new Date(a.date) - new Date(b.date)); // Terlama dulu
            }

            const total = filtered.length;
            const start = (page - 1) * perPage;
            const paginated = filtered.slice(start, start + perPage);

            resolve({
                data: paginated,
                total: total,
                page: page,
                totalPages: Math.ceil(total / perPage)
            });
        }, 500);
    });
}

function getNewsDetail(id) {
    return new Promise(resolve => {
        setTimeout(() => {
            const news = newsDatabase.find(n => n.id === parseInt(id));
            resolve(news || null);
        }, 300);
    });
}

function incrementViews(id) {
    const news = newsDatabase.find(n => n.id === parseInt(id));
    if (news) {
        news.views += 1;
        // Simpan ke localStorage untuk persist data
        localStorage.setItem('newsDatabase', JSON.stringify(newsDatabase));
        return news.views;
    }
    return null;
}

// Get random other news (exclude current news)
function getOtherNews(currentId, limit = 2) {
    return new Promise((resolve) => {
        setTimeout(() => {
            // Filter out current news
            const filtered = newsDatabase.filter(n => n.id !== parseInt(currentId));

            // Shuffle array untuk random
            const shuffled = filtered.sort(() => 0.5 - Math.random());

            // Ambil sesuai limit
            const result = shuffled.slice(0, limit);

            resolve(result);
        }, 500);
    });
}

